const mongoose = require('mongoose');

const ReviewSchema = new mongoose.Schema({
  workshopId: {
    type: String,
    required: true,
    index: true
  },
  name: {
    type: String,
    required: true
  },
  rating: {
    type: Number,
    required: true,
    min: 1,
    max: 5
  },
  comment: {
    type: String,
    required: true
  },
  createdAt: {
    type: Date,
    default: Date.now
  }
});

module.exports = mongoose.model('Review', ReviewSchema);
